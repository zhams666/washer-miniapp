import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'sql', 'migrations');
const outputFile = join(root, 'sql', 'postgresql', '001_cloudbase_init.sql');

function splitTopLevel(value) {
  const parts = [];
  let start = 0;
  let depth = 0;
  let quote = null;
  for (let index = 0; index < value.length; index += 1) {
    const character = value[index];
    if (quote) {
      if (character === quote && value[index - 1] !== '\\') {
        quote = null;
      }
      continue;
    }
    if (character === "'") {
      quote = character;
    } else if (character === '(') {
      depth += 1;
    } else if (character === ')') {
      depth -= 1;
    } else if (character === ',' && depth === 0) {
      parts.push(value.slice(start, index));
      start = index + 1;
    }
  }
  parts.push(value.slice(start));
  return parts.map((part) => part.trim()).filter(Boolean);
}

function normalize(source) {
  return source
    .replace(/^SET NAMES utf8mb4;\s*/gim, '')
    .replace(/SELECT DATABASE\(\);\s*/gim, '')
    .replace(/^--.*$/gm, '')
    .replace(/\)\s*ENGINE=InnoDB\s+DEFAULT CHARSET=utf8mb4(?:\s+COMMENT\s*=\s*'[^']*')?\s*;?/gi, ');')
    .replace(/\s+COMMENT\s+'[^']*'/gi, '')
    .replace(/\s+AFTER\s+`[^`]+`/gi, '')
    .replace(/\s+ON UPDATE CURRENT_TIMESTAMP/gi, '')
    .replace(/`/g, '')
    .replace(/\bBIGINT\s+NOT NULL\s+AUTO_INCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL')
    .replace(/\bTINYINT\b/gi, 'SMALLINT')
    .replace(/\bDATETIME\b/gi, 'TIMESTAMP')
    .replace(/\bLONGTEXT\b/gi, 'TEXT')
    .replace(/\bJSON\b/gi, 'JSONB')
    .replace(/\bNOW\(\)/gi, 'CURRENT_TIMESTAMP')
    .replace(/\)\s+AS new\s*\nON DUPLICATE KEY UPDATE/gi, ')\nON CONFLICT DO UPDATE SET')
    .replace(/ON DUPLICATE KEY UPDATE/gi, 'ON CONFLICT DO UPDATE SET')
    .replace(/\bnew\.([a-z_]+)/gi, 'EXCLUDED.$1');
}

function convertCreateTable(statement) {
  const match = statement.match(/^CREATE TABLE IF NOT EXISTS\s+([a-z_]+)\s*\(([\s\S]*)\)$/i);
  if (!match) {
    return [statement];
  }

  const [, tableName, rawBody] = match;
  const indexes = [];
  const lines = splitTopLevel(rawBody)
    .map((line) => line.replace(/\s+/g, ' ').trim())
    .filter(Boolean)
    .map((line) => {
      const indexMatch = line.match(/^KEY\s+([a-z_]+)\s*\((.+)\)$/i);
      if (indexMatch) {
        indexes.push(`CREATE INDEX IF NOT EXISTS ${tableName}__${indexMatch[1]} ON ${tableName} (${indexMatch[2]})`);
        return null;
      }
      return line.replace(/^UNIQUE KEY\s+([a-z_]+)\s*\((.+)\)$/i, 'CONSTRAINT $1 UNIQUE ($2)');
    })
    .filter(Boolean);

  return [`CREATE TABLE IF NOT EXISTS ${tableName} (\n  ${lines.join(',\n  ')}\n)`, ...indexes];
}

function convertAlterTable(statement) {
  const match = statement.match(/^ALTER TABLE\s+([a-z_]+)\s+([\s\S]*)$/i);
  if (!match) {
    return [statement];
  }

  const [, tableName, rawClauses] = match;
  return splitTopLevel(rawClauses).flatMap((rawClause) => {
    const clause = rawClause.replace(/\s+/g, ' ').trim();
    const addIndex = clause.match(/^ADD KEY\s+([a-z_]+)\s*\((.+)\)$/i);
    if (addIndex) {
      return [`CREATE INDEX IF NOT EXISTS ${tableName}__${addIndex[1]} ON ${tableName} (${addIndex[2]})`];
    }
    const addUnique = clause.match(/^ADD UNIQUE KEY\s+([a-z_]+)\s*\((.+)\)$/i);
    if (addUnique) {
      return [`ALTER TABLE ${tableName} ADD CONSTRAINT ${addUnique[1]} UNIQUE (${addUnique[2]})`];
    }
    const dropIndex = clause.match(/^DROP INDEX\s+([a-z_]+)$/i);
    if (dropIndex) {
      return [`ALTER TABLE ${tableName} DROP CONSTRAINT IF EXISTS ${dropIndex[1]}`];
    }
    const modifyColumn = clause.match(/^MODIFY COLUMN\s+([a-z_]+)\s+(.+)$/i);
    if (modifyColumn) {
      const [, columnName, definition] = modifyColumn;
      const type = definition.match(/^([A-Z]+(?:\([^)]*\))?)/i)?.[1];
      const statements = [];
      if (type) {
        statements.push(`ALTER TABLE ${tableName} ALTER COLUMN ${columnName} TYPE ${type}`);
      }
      const defaultValue = definition.match(/\sDEFAULT\s+([^\s,]+)/i)?.[1];
      if (defaultValue) {
        statements.push(`ALTER TABLE ${tableName} ALTER COLUMN ${columnName} SET DEFAULT ${defaultValue}`);
      }
      if (/\bNOT NULL\b/i.test(definition)) {
        statements.push(`ALTER TABLE ${tableName} ALTER COLUMN ${columnName} SET NOT NULL`);
      }
      return statements;
    }
    return [`ALTER TABLE ${tableName} ${clause.replace(/^ADD COLUMN\s+/i, 'ADD COLUMN ')}`];
  });
}

function convertStatement(statement) {
  const trimmed = statement.trim();
  if (!trimmed) {
    return [];
  }
  if (/^CREATE TABLE /i.test(trimmed)) {
    return convertCreateTable(trimmed);
  }
  if (/^ALTER TABLE /i.test(trimmed)) {
    return convertAlterTable(trimmed);
  }
  return [trimmed];
}

function postProcess(statements) {
  const conflictTargets = {
    franchisee: 'id',
    mini_admin_staff: 'id',
    mini_admin_staff_store: 'staff_id, store_id'
  };

  return statements.map((statement) => {
    const tableName = statement.match(/^INSERT INTO\s+([a-z_]+)/i)?.[1]?.toLowerCase();
    const conflictTarget = conflictTargets[tableName];
    return statement
      .replace(
        /UPDATE mini_admin_staff_store ss\s+JOIN store s ON s\.id = ss\.store_id\s+SET ss\.is_primary = 1\s+WHERE ss\.staff_id = 1\s+AND s\.id = \(SELECT MIN\(id\) FROM store\)/i,
        'UPDATE mini_admin_staff_store AS ss SET is_primary = 1 FROM store AS s WHERE s.id = ss.store_id AND ss.staff_id = 1 AND s.id = (SELECT MIN(id) FROM store)'
      )
      .replace(
        'ON CONFLICT DO UPDATE SET',
        conflictTarget ? `ON CONFLICT (${conflictTarget}) DO UPDATE SET` : 'ON CONFLICT DO NOTHING'
      );
  });
}

const migrationFiles = (await readdir(migrationsDir))
  .filter((file) => file.endsWith('.sql'))
  .sort();
const source = normalize((await Promise.all(
  migrationFiles.map(async (file) => `-- Source: ${file}\n${await readFile(join(migrationsDir, file), 'utf8')}`)
)).join('\n\n'));
const statements = postProcess(source.split(';').flatMap(convertStatement));

const helperSql = `
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE
  target_table text;
BEGIN
  FOR target_table IN
    SELECT DISTINCT columns.table_name
    FROM information_schema.columns AS columns
    WHERE columns.table_schema = current_schema() AND columns.column_name = 'updated_at'
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%s_updated_at ON %I', target_table, target_table);
    EXECUTE format(
      'CREATE TRIGGER trg_%s_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
      target_table,
      target_table
    );
  END LOOP;
END;
$$;

DO $$
DECLARE
  target_table text;
BEGIN
  FOR target_table IN
    SELECT DISTINCT columns.table_name
    FROM information_schema.columns AS columns
    WHERE columns.table_schema = current_schema() AND columns.column_name = 'id'
  LOOP
    EXECUTE format(
      'SELECT setval(pg_get_serial_sequence(%L, %L), COALESCE((SELECT MAX(id) FROM %I), 1), true)',
      target_table,
      'id',
      target_table
    );
  END LOOP;
END;
$$;
`;

await mkdir(dirname(outputFile), { recursive: true });
await writeFile(
  outputFile,
  `${statements.map((statement) => `${statement};`).join('\n\n')}\n${helperSql}`,
  'utf8'
);

console.log(`Generated ${outputFile} from ${migrationFiles.length} MySQL migration files.`);
